import type { Metadata, Viewport } from "next";
import { Geist, Geist_Mono, Instrument_Serif } from "next/font/google";
import { ThemeProvider } from "@/components/theme-provider";
import { site } from "@/data/site";
import { getSiteUrl, isTodo } from "@/lib/utils";
import "./globals.css";

/*
 * FONTS
 * next/font downloads these at build time and serves them from your own
 * domain, so there's no layout shift and no request to Google from visitors.
 */
const geistSans = Geist({ variable: "--font-geist-sans", subsets: ["latin"] });
const geistMono = Geist_Mono({ variable: "--font-geist-mono", subsets: ["latin"] });
const instrumentSerif = Instrument_Serif({
  variable: "--font-instrument-serif",
  subsets: ["latin"],
  weight: "400",
  style: ["normal", "italic"],
});

const siteUrl = getSiteUrl();
const title = `${site.name} | ${site.role} (Next.js, Supabase, Stripe, AI)`;

/*
 * SEO + SOCIAL PREVIEW TAGS
 * Next.js turns this object into <meta> tags in the page <head>.
 * The preview image itself is generated by app/opengraph-image.tsx.
 */
export const metadata: Metadata = {
  metadataBase: new URL(siteUrl),
  title,
  description: site.description,
  keywords: [
    "SaaS MVP developer",
    "Next.js developer",
    "Supabase developer",
    "Stripe integration",
    "AI integration",
    "multi-tenant SaaS",
    "hire on Fiverr",
  ],
  authors: [{ name: site.name, url: site.links.github }],
  alternates: { canonical: "/" },
  openGraph: {
    type: "website",
    url: "/",
    siteName: `${site.name} | ${site.role}`,
    title,
    description: site.description,
    locale: "en_US",
  },
  twitter: {
    card: "summary_large_image",
    title,
    description: site.description,
  },
  robots: { index: true, follow: true },
};

// Colors the mobile browser bar to match the page in each theme.
export const viewport: Viewport = {
  themeColor: [
    { media: "(prefers-color-scheme: light)", color: "#f5f4ef" },
    { media: "(prefers-color-scheme: dark)", color: "#0b0b0a" },
  ],
};

/*
 * Structured data (JSON-LD) helps Google understand who you are
 * and what you offer. It's invisible on the page.
 */
const jsonLd = {
  "@context": "https://schema.org",
  "@type": "Person",
  name: site.name,
  jobTitle: site.role,
  url: siteUrl,
  sameAs: [site.links.github, site.links.fiverr],
  ...(isTodo(site.links.email) ? {} : { email: `mailto:${site.links.email}` }),
  knowsAbout: ["Next.js", "Supabase", "Stripe", "AI integration", "SaaS"],
};

export default function RootLayout({ children }: { children: React.ReactNode }) {
  return (
    // suppressHydrationWarning: next-themes and our "js" class change <html>
    // attributes before React loads, which is expected.
    <html
      lang="en"
      suppressHydrationWarning
      className={`${geistSans.variable} ${geistMono.variable} ${instrumentSerif.variable}`}
    >
      <head>
        {/* Marks that JavaScript is running, so scroll animations can start hidden. */}
        <script dangerouslySetInnerHTML={{ __html: "document.documentElement.classList.add('js')" }} />
        <script
          type="application/ld+json"
          dangerouslySetInnerHTML={{ __html: JSON.stringify(jsonLd) }}
        />
      </head>
      <body className="min-h-dvh bg-bg text-ink">
        <ThemeProvider>{children}</ThemeProvider>
      </body>
    </html>
  );
}
